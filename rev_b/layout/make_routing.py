#!/usr/bin/env python3
"""Write rev_b/layout/routing.json (the kicad-agentic-routing config) from netclasses.py."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import netclasses as N  # noqa: E402


# Feedback-loop keep-away (soft): the PI plates, the return plate and the speaker-level feedback lines are
# priced within 3 mm of the loop's early high-impedance nodes (a coupling there closes a loop around the
# power section: the preamp's coupling check found this case).
AGG = ["DRV_A", "DRV_B", "P1B", "SPK_CL", "SPK_CR", "SPK_LD", "FB_8R", "SEND_SRC"]
VICTIM = ["PRE_IN", "CI", "G1A", "RETURN_SIG", "RC", "NW", "DMX", "WMX", "M", "G1B", "ATT_IN", "ATT1", "ATT2", "ATT3",
          "ATT4", "ATT_OUT", "PIX", "G2A"]


def pats(names):
    return [p for n in names for p in (n, "*/" + n)]


cfg = {
    "_comment": "PI + FX rev B routing (KiCadRoutingTools via the kicad-agentic-routing skill). Generated by make_routing.py.",
    "project": "../kicad/tube_pi_fxloop_revb",
    "krt": "~/dev/KiCadRoutingTools",
    "route_args": ["--layers", "F.Cu", "B.Cu", "--grid-step", "0.1", "--fab-tier", "standard", "--no-fix-drc-settings",
                   "--escalation", "board", "--via-size", "0.8", "--via-drill", "0.3",
                   "--keep-away", ",".join(pats(AGG)) + ":" + ",".join(pats(VICTIM)) + ":3", "--keep-away-cost", "3"],
    "default_layer_costs": [1, 2],
    "planes": {"F.Cu": ["GND", "*/GND"], "B.Cu": ["GND", "*/GND"]},
    "signal_layers": ["F.Cu", "B.Cu"],
    "power_nets": ["GND", "GNDD", "+5V", "+15V", "-15V", "HTR1", "HTR2", "*/HTR1", "*/HTR2"],
    "groups": {"hv": pats(N.HV), "mv": pats(N.MV), "hiz": pats(N.HIZ), "audio": pats(N.AUDIO), "gate": pats(N.GATE),
               "logic": pats(N.LOGIC), "coil": pats(N.COIL), "supply": pats(N.SUPPLY)},
}
json.dump(cfg, open(os.path.join(HERE, "routing.json"), "w"), indent=1)
print("routing.json:", {k: len(v) // 2 for k, v in cfg["groups"].items()})
