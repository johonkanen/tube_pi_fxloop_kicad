#!/usr/bin/env python3
"""Thermal foldback of the SMD regulator variant (docs/preamp_regulator.md, rev B reference).

Copied from tube_amplifier_kicad sim/preamp_supply (2026-11-22) for the PI + FX rev B regulators;
only OUTPUTS changed (this board's loads and resistor strings).

The pass device is a DPAK (STD4N80K5) on a copper pour; the current-limit NPN (Q1) sits on the same
pour, so its Vbe (about -2 mV/K) falls as the pour heats and the foldback deepens. This script:
  1. sweeps the circuit temperature (ngspice .temp: the whole circuit, so mostly Q1's Vbe) and
     records the normal current limit, the short-circuit current and dissipation, start-up and
     recovery after a short;
  2. solves the steady state of a short with a simple thermal model: pour temperature
     Tp = Ta + Rth_pa * P, Q1 at Ta + k * (Tp - Ta), junction Tj = Tp + Rth_jp * P;
  3. gives the normal-operation pour and Q1 temperatures and the remaining current-limit margin.

Writes results/thermal_foldback.md; raw data in out/thermal/.
Usage: python3 run_thermal_foldback.py
"""
import os
import shutil
import sys
from multiprocessing import Pool

import numpy as np

import reg

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')
OUT = os.path.join(HERE, 'out', 'thermal')

# SMD variant per output: Rs chosen so the normal limit stays above the load with Q1 hot.
OUTPUTS = {
    # PI + FX rev B (sheet 05): rev B reference parts, R3 = 3 x 270k (810k), bleed 3 x 150k (450k).
    # Loads are this board's stage currents (the bleed is in the model): B+PI = the PI tail 2.1 mA,
    # B+FX = send CF 1.35 mA + return stage 1.04 mA. The 8 mA rows are the master repo's planning load.
    'B+PI': dict(zeners=(130, 130, 130), iload=0.0021, rs=20.0, r3=810e3, rbleed=450e3),
    'B+FX': dict(zeners=(150, 180), iload=0.0024, rs=16.0, r3=810e3, rbleed=450e3),
    'B+PI 8 mA': dict(zeners=(130, 130, 130), iload=0.008, rs=20.0, r3=810e3, rbleed=450e3),
    'B+FX 8 mA': dict(zeners=(150, 180), iload=0.008, rs=16.0, r3=810e3, rbleed=450e3),
}
TEMPS = [0, 27, 50, 70, 85, 100, 115, 130, 145]
TESTS = ['load', 'short', 'startup']
# Thermal model (estimates, to confirm on the bench):
RTH_PA = tuple(float(x) for x in os.environ.get('RTH_PA', '30,40,50').split(','))  # pour to ambient, K/W
# (a few cm2 of 2 oz copper, components-down board; layout first pass: RTH_PA=15,20,25 -> thermal_foldback_layout.md)
K_COUPLE = 0.8                # Q1 rise as a fraction of the pour rise (SOT-23 on the same pour)
RTH_JP = 3.0                  # junction to pour, K/W (2.08 K/W junction-case plus the solder joint)
TAMB = (25.0, 50.0, 60.0, 70.0)  # room to 70 C under the plate (review U17 / N61 design figure)


def job(args):
    name, t, test = args
    wd = os.path.join(OUT, name.replace('+', '').replace(' ', '_').replace(',', ''), f'{t}', test)
    os.makedirs(wd, exist_ok=True)
    v, _ = reg.run(test, dict(OUTPUTS[name], temp=t), wd)
    if test == 'load':
        d = np.loadtxt(os.path.join(wd, 'load.txt'))
        v['lim'] = d[np.argmax(d[:, 1] < d[0, 1] - 5), 0]
    return args, v


def steady_short(T, P, ta, rth):
    """Fixed point of the short: Q1 temperature Tq with P(Tq) from the sweep."""
    tq = ta
    for _ in range(200):
        p = float(np.interp(tq, T, P))
        tp = ta + rth * p
        tq = 0.5 * tq + 0.5 * (ta + K_COUPLE * (tp - ta))
    return tq, tp, p, tp + RTH_JP * p


def main():
    os.makedirs(RES, exist_ok=True)
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    with Pool() as pool:
        res = dict(pool.map(job, [(n, t, x) for n in OUTPUTS for t in TEMPS for x in TESTS]))
    L = ['# Regulator thermal foldback (SMD variant): simulation results\n',
         '> Generated by `run_thermal_foldback.py`; do not edit. Design: docs/preamp_regulator.md.',
         '> ngspice `.temp` sets the whole circuit, so the sweep stands for Q1\'s temperature (the zener',
         '> models have no tempco). Generic device models; thermal figures are estimates.\n',
         '## Sweep against Q1 temperature\n']
    for n, p in OUTPUTS.items():
        rd = f', drain resistor {p["rdrain"] / 1e3:.1f}k' if p.get('rdrain') else ''
        L += [f'### {n}: Rs {p["rs"]:.0f} Ω, R3 {p["r3"] / 1e3:.0f}k{rd}, load {p["iload"] * 1e3:.0f} mA\n',
              '| Q1 (°C) | Normal limit (mA) | Short: I (mA) | Short: P pass (W) | Start-up Vout (V) | Recovers after short |',
              '|---|---|---|---|---|---|']
        for t in TEMPS:
            l, s, u = (res[(n, t, x)] for x in TESTS)
            rec = abs(s.get('vrec', 0) - s.get('vbefore', 0)) < 5
            L.append(f'| {t} | {l["lim"] * 1e3:.1f} | {s.get("ishort", 0) * 1e3:.1f} | {s.get("pshort", 0):.2f} | '
                     f'{u.get("vfinal", 0):.0f} | {"yes" if rec else "NO"} |')
        L.append('')
    L += ['## Steady state into a short\n',
          f'Q1 rise = {K_COUPLE} x pour rise; junction = pour + {RTH_JP:.0f} K/W x P.\n',
          '| Output | Ta (°C) | Pour to ambient (K/W) | Q1 (°C) | Pour (°C) | P pass (W) | Pass junction (°C) |',
          '|---|---|---|---|---|---|---|']
    for n in OUTPUTS:
        T = np.array(TEMPS, float)
        P = np.array([res[(n, t, 'short')].get('pshort', 0.0) for t in TEMPS])
        for ta in TAMB:
            for rth in RTH_PA:
                tq, tp, pw, tj = steady_short(T, P, ta, rth)
                L.append(f'| {n} | {ta:.0f} | {rth:.0f} | {tq:.0f} | {tp:.0f} | {pw:.2f} | {tj:.0f} |')
    L += ['', '## Normal operation\n',
          'P pass is M2 only; a drain resistor dissipates Rd x I^2 off the pour. "Starts" = start-up and',
          'recovery after a short both work at that Q1 temperature in the sweep.\n',
          '| Output | Ta (°C) | Pour to ambient (K/W) | P pass (W) | P drain R (W) | Q1 (°C) | Normal limit at that Q1 (mA) | Load (mA) | Starts |',
          '|---|---|---|---|---|---|---|---|---|']
    for n, p in OUTPUTS.items():
        T = np.array(TEMPS, float)
        lim = np.array([res[(n, t, 'load')]['lim'] for t in TEMPS])
        vout = res[(n, 27, 'startup')]['vfinal']
        rdr = p.get('rdrain', 0.0)
        it = p['iload'] + vout / p.get('rbleed', 470e3)   # PI + FX copy: the bleed current passes M2 too
        pn = (430.0 - rdr * it - vout) * it
        ok = [res[(n, t, 'startup')].get('vfinal', 0) > vout - 5 and
              abs(res[(n, t, 'short')].get('vrec', 0) - res[(n, t, 'short')].get('vbefore', 0)) < 5 for t in TEMPS]
        for ta in TAMB:
            for rth in RTH_PA:
                tq = ta + K_COUPLE * rth * pn
                above = [o for t, o in zip(TEMPS, ok) if t >= tq]   # the sweep point at or above tq must pass
                starts = bool(above) and above[0]
                L.append(f'| {n} | {ta:.0f} | {rth:.0f} | {pn:.2f} | {rdr * p["iload"] ** 2:.2f} | {tq:.0f} | '
                         f'{np.interp(tq, T, lim) * 1e3:.1f} | {p["iload"] * 1e3:.0f} | {"yes" if starts else "NO"} |')
    with open(os.path.join(RES, os.environ.get('RESULT', 'thermal_foldback.md')), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    sys.exit(main())
