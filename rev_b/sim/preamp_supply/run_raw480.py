"""PI + FX rev B, third pass: the B+PI and B+FX regulators with the raw rail at 430 / 450 / 480 V
(480 V accepted as a transient and as the trip level, sustained <= 450 V; user 2026-11-23, V7),
repeating the preamp's check (docs/preamp_regulator.md "Raw rail up to 480 V"): normal current limit,
start-up and recovery after a short, against Q1's temperature (ngspice .temp, as run_thermal_foldback).
This board's loads and parts: R3 810k, bleed 450k, Rs 20R / 16R, no drain resistor.
Writes results/raw480.md.    python3 run_raw480.py
"""
import os
import shutil
from multiprocessing import Pool

import numpy as np

import reg

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'out', 'raw480')
OUTPUTS = {
    'B+PI': dict(zeners=(130, 130, 130), iload=0.0021, rs=20.0, r3=810e3, rbleed=450e3),
    'B+FX': dict(zeners=(150, 180), iload=0.0024, rs=16.0, r3=810e3, rbleed=450e3),
}
RAWS = (430.0, 450.0, 480.0)
TEMPS = (27, 70, 80, 85, 90, 95, 100)
TESTS = ('load', 'short', 'startup')


def job(a):
    n, vr, t, test = a
    wd = os.path.join(OUT, n.replace('+', ''), f'{vr:.0f}', f'{t}', test)
    os.makedirs(wd, exist_ok=True)
    v, _ = reg.run(test, dict(OUTPUTS[n], vraw=vr, temp=t), wd)
    if test == 'load':
        d = np.loadtxt(os.path.join(wd, 'load.txt'))
        v['lim'] = d[np.argmax(d[:, 1] < d[0, 1] - 5), 0]
    return a, v


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    jobs = [(n, vr, t, x) for n in OUTPUTS for vr in RAWS for t in TEMPS for x in TESTS]
    with Pool() as p:
        res = dict(p.map(job, jobs))
    L = ['# B+PI / B+FX at 430-480 V raw', '', '> Generated by `run_raw480.py`; generic models; .temp = Q1 temperature.', '']
    for n, p in OUTPUTS.items():
        L += [f'## {n} (load {p["iload"] * 1e3:.1f} mA + bleed)', '',
              '| Raw (V) | Q1 (°C) | Normal limit (mA) | Short: I (mA) / P pass (W) | Start-up Vout (V) | Recovers after short |',
              '|---|---|---|---|---|---|']
        for vr in RAWS:
            vnom = res[(n, vr, 27, 'startup')].get('vfinal', 0)
            for t in TEMPS:
                l, s, u = (res[(n, vr, t, x)] for x in TESTS)
                rec = abs(s.get('vrec', 0) - s.get('vbefore', 0)) < 5
                ok = u.get('vfinal', 0) > vnom - 5
                L.append(f'| {vr:.0f} | {t} | {l["lim"] * 1e3:.1f} | {s.get("ishort", 0) * 1e3:.1f} / {s.get("pshort", 0):.2f} | '
                         f'{u.get("vfinal", 0):.0f}{"" if ok else " (no start)"} | {"yes" if rec else "NO"} |')
        L.append('')
    os.makedirs(os.path.join(HERE, 'results'), exist_ok=True)
    open(os.path.join(HERE, 'results', 'raw480.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
