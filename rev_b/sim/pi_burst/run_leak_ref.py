"""PI + FX rev B, third pass: where the PI grid leaks return (docs/output_stage_stability.md section 5,
"PI finding"). The burst test of run_dynamics.py / run_coupling_blocking.py (copied from
tube_amplifier_kicad sim/pi_nfb at ca741ff) with the decided power coupling 220n / 91k, EL34, Rf 100k,
V_ANODE 400 V, speaker model: 300 ms of 100 Hz at +13 dB (13 V, the real maximum drive) and +20 dB
(28 V) over the 5 % onset, on a 1 kHz probe.

Cases:
- tail: the leaks returned to the CCS tail top (the rev B PI as drawn in the second pass, 5b66d6b);
- divider: the leaks returned to the third pass's reference: 2x 820k from B+PI decoupled (386 V)
  to PI_REF, 100k to GND (22.2 V), 10 uF;
- fixed9: an ideal 9 V, the study's reference case.
Writes results/leak_ref.md.    python3 run_leak_ref.py
"""
import os
from multiprocessing import Pool

os.environ.setdefault('OMP_NUM_THREADS', '1')
import numpy as np

import stability as S
import run_dynamics as D

HERE = os.path.dirname(os.path.abspath(__file__))
REFS = {'tail': None, 'divider': (386.0, 1.64e6, 100e3, 10e-6), 'fixed9': 9.0}
LABEL = {'tail': 'tail top (second pass as drawn)', 'divider': 'decoupled divider 22 V (third pass)',
         'fixed9': 'ideal 9 V (study reference)'}
D.NODES = ['out', 'gl1', 'gl3', 'pi_gx', 'pi_top']


def case(a):
    ref, rel = a

    def simulate(va, _fb, vin, tstop, stage_p=None, pi=None):
        return S.tran(va, vin, tstop, D.STEP, D.NODES, tube='EL34', load='spk95', cc=220e-9, rgl=91e3,
                      fb='100k', pi_leak_ref=REFS[ref])
    D.simulate = simulate
    k, r = D.burst_case(((ref, rel), 400.0, '100k', rel, 220e-9))
    return k, r


def main():
    jobs = [(r, rel) for r in REFS for rel in (13, 20)]
    with Pool(len(jobs)) as p:
        res = dict(p.map(case, jobs, chunksize=1))
    md = ["# PI grid-leak return: burst recovery", "",
          "Generated by `run_leak_ref.py`. 220n / 91k per power tube, 4x EL34, 400 V, Rf 100k + 22p, speaker model;",
          "300 ms of 100 Hz on a 1 kHz probe 20 dB under the onset (2.81 V). PI grid shift = the PI input grid's",
          "DC level (20 ms average) against before the burst: up = the common mode pumped up; 'back' = time",
          "after the burst until within 1 V (the run ends 1 s after the burst, so 970 ms = not recovered).", "",
          "| Leak return | Burst | Power grid shift / back within 1 V | PI grid shift down / up / back within 1 V | Probe dip / back within 1 dB | LF thump |",
          "|---|---|---|---|---|---|"]
    for ref in REFS:
        for rel in (13, 20):
            r = res[(ref, rel)]
            if 'error' in r:
                md.append(f"| {LABEL[ref]} | +{rel} dB | failed: {r['error'][-80:]} | | | |")
                continue
            up = float(np.max(r['pishift']))
            md.append(f"| {LABEL[ref]} | +{rel} dB | {r['smax']:+.1f} V / {r['tbias']*1e3:.0f} ms | "
                      f"{r['pimax']:+.1f} / {up:+.1f} V / {r['tpi']*1e3:.0f} ms | {r['dip']:+.1f} dB / {r['trec']*1e3:.0f} ms | {r['thump']:.1f} V pk |")
    with open(os.path.join(HERE, 'results', 'leak_ref.md'), 'w') as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == '__main__':
    main()
