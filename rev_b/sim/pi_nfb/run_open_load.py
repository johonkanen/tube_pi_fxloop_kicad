#!/usr/bin/env python3
"""Rev B check of the PI + feedback loop (SPECIFICATION PI-3, SAFE-5): loop margins with the
rev B coupling caps (PI input 10n, second grid 22n, power coupling 47n), the constant-current
tail with equal 100k plates, and the speaker, an 8 ohm resistor or NO load (open output).

Copy of tube_amplifier_kicad sim/pi_nfb (nfb.py) and sim/power_stage (stage.py), with three
additions in nfb.py: load='open' (1 Mohm on the 8 ohm tap), a real CCS (finite output
resistance rccs and capacitance cccs) and the W24 cable + power tube input capacitance (cdrv).

Writes results/open_load.md. About 1-2 minutes.
"""
import os
from multiprocessing import Pool

import numpy as np

import nfb

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')

BASE = dict(ccs=2.07e-3, ra1=100e3, cin=10e-9, cg2=22e-9)
REAL = dict(rccs=1e6, cccs=30e-12, cdrv=60e-12, rs=25e3)   # DN2540 + 1k source R; W24 + 2 EL34 per side; attenuator source
CASES = [  # key, label, PI overrides, power stage overrides
    ('a', 'pi_nfb proposal as simulated: 10n / 22n / 47n, power grid leak 220k', dict(BASE), dict(cc=47e-9, rgl=220e3)),
    ('b', 'same, power grid leak 100k (interfaces.md section 10 text)', dict(BASE), dict(cc=47e-9, rgl=100e3)),
    ('c', 'b + real CCS, W24 / power tube capacitance, 25k source', dict(BASE, **REAL), dict(cc=47e-9, rgl=100e3)),
    ('d', 'c with second-grid cap 100n', dict(BASE, **REAL, cg2=100e-9), dict(cc=47e-9, rgl=100e3)),
    ('e', 'c with second-grid cap 220n (dominant pole)', dict(BASE, **REAL, cg2=220e-9), dict(cc=47e-9, rgl=100e3)),
    ('f', 'c with power grid leak 220k', dict(BASE, **REAL), dict(cc=47e-9, rgl=220e3)),
    ('g', 'f with second-grid cap 220n', dict(BASE, **REAL, cg2=220e-9), dict(cc=47e-9, rgl=220e3)),
    ('h', 'c with power coupling 100n, grid leak 220k', dict(BASE, **REAL), dict(cc=100e-9, rgl=220e3)),
    ('i', 'c with second-grid cap 4.7n, power coupling 100n / 220k', dict(BASE, **REAL, cg2=4.7e-9), dict(cc=100e-9, rgl=220e3)),
]
LOADS = ('speaker', 'resistor', 'open', 'r:100')   # r:100 = no speaker, 100 ohm safety load on the 8 ohm tap
K = dict(mode='grid2', pol=-1)


def job(args):
    key, pi, sp, load, va, pr, rr = args
    try:
        f, T = nfb.loop_gain(va, pr, rr, load=load, pi=pi, stage_p=sp, **K)
    except Exception as e:  # noqa: BLE001
        return (key, load, va, pr, rr), dict(err=str(e)[:300])
    pms, gm = nfb.margins(f, T)
    lf = [(fc, pm) for fc, pm in pms if fc < 1e3]
    hf = [(fc, pm) for fc, pm in pms if fc >= 1e3]
    t1k = float(np.abs(np.interp(1e3, f, np.abs(T))))
    tmax_lf = float(np.max(np.abs(T[f < 50]))) if np.any(f < 50) else float('nan')
    return (key, load, va, pr, rr), dict(lf=lf, hf=hf, gm=gm, t1k=t1k, tlf=tmax_lf)


def main():
    os.makedirs(RES, exist_ok=True)
    jobs = [(k, pi, sp, ld, va, pr, rr) for k, _, pi, sp in CASES for ld in LOADS
            for va in (400.0, 200.0) for pr, rr in ((0, 0), (1, 0), (0, 1), (1, 1))]
    with Pool(min(30, os.cpu_count() or 4)) as p:
        res = dict(p.map(job, jobs))
    md = ['# Rev B PI loop margins with an open output', '',
          'Generated by `run_open_load.py`. Loop broken at the speaker end of Rf; Rf 100k + 22p; 4x EL34;',
          'V_ANODE 400 and 200 V; presence and resonance at 0 / 100 %. Worst case over those per load.', '',
          '| Case | Load | Feedback at 1 kHz | Worst LF phase margin (at Hz) | Worst HF phase margin (at kHz) | Gain margin |',
          '|---|---|---|---|---|---|']
    for k, lab, _, _ in CASES:
        for ld in LOADS:
            rs = [r for a, r in res.items() if a[0] == k and a[1] == ld]
            errs = [r for r in rs if 'err' in r]
            rs = [r for r in rs if 'err' not in r]
            if not rs:
                md.append(f'| {lab} | {ld} | failed | | | |')
                continue
            lf = min((x for r in rs for x in r['lf']), key=lambda x: x[1], default=None)
            hf = min((x for r in rs for x in r['hf']), key=lambda x: x[1], default=None)
            gm = min(r['gm'] for r in rs)
            fb = min(20 * np.log10(1 + r['t1k']) for r in rs)
            lfs = f'{lf[1]:.0f}° ({lf[0]:.1f})' if lf else 'no LF crossing'
            hfs = f'{hf[1]:.0f}° ({hf[0] / 1e3:.0f})' if hf else 'no HF crossing'
            gms = 'none' if gm > 90 else f'{gm:.1f} dB'
            md.append(f'| {lab} | {ld} | {fb:.1f} dB | {lfs} | {hfs} | {gms}{" (" + str(len(errs)) + " runs failed)" if errs else ""} |')
    open(os.path.join(RES, 'open_load.md'), 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
