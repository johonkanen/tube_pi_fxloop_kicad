#!/usr/bin/env python3
"""PI + FX rev B, third pass: the normalled return at full level (user V15, 2026-11-23: accepted as is).
Nothing plugged into the rear jacks and both rear pots at full: the RETURN jack is normalled to the
SEND LEVEL pot's wiper, so RETURN_SIG carries the full send level, up to 17 V peak (the preamp's full
scale through the send follower). Series mode (wet branch on), pad off and on.

Source at the RETURN LEVEL pot's top (pot at full): a 0.3 V / 3 kHz probe all the time plus a 300 ms
burst of 1 kHz at 17 V peak (0.10-0.40 s); run to 1.0 s. Reports the return stage's grid current, the
node levels, the JFET gate, the DC shifts after the burst and the probe's recovery.
Circuit: fx_revb.py. Writes results/normalled.md.    python3 run_normalled.py
"""
import os
from multiprocessing import Pool

import numpy as np

import fx_revb as F
from simrun import run

HERE = os.path.dirname(os.path.abspath(__file__))
T0, T1, TEND, STEP = 0.10, 0.40, 1.0, 5e-6
NODES = ['rsig', 'nw', 'wmx', 'm', 'mg', 'rk', 'rp', 'gwj', 'OUT']


def job(a):
    amp, pad = a
    net, out = F.netlist('series', src='off', ret_src='sin', ret_amp=amp, pad=pad)
    old = f'Vret rj0 0 SIN(0 {amp} 1k)'
    assert old in net
    tr = 2e-3
    net = net.replace(old, f"Bret rj0 0 V = {{0.3*sin(2*pi*3000*time) + {amp}*sin(2*pi*1000*time)"
                           f"*0.25*(1+tanh((time-{T0})/{tr}))*(1-tanh((time-{T1})/{tr}))}}")
    nodes = [n if n != 'OUT' else out for n in NODES]
    vecs = ' '.join(f'v({n})' for n in nodes)
    _, f, _, o = run(net, f'tran {STEP} {TEND} 0 {STEP}\nlinearize {vecs}\nwrdata w.txt {vecs}')
    if 'w.txt' not in f:
        return a, dict(error=o[-500:])
    w = f['w.txt']
    t = w[:, 0]
    v = {n: w[:, 1 + 2 * i] for i, n in enumerate(NODES)}
    dt = t[1] - t[0]

    def win(x, ta, tb):
        return x[(t >= ta) & (t < tb)]

    def tone(x, ta, tb, fr):
        y = win(x, ta, tb)
        y = y - y.mean()
        Y = np.abs(np.fft.rfft(y * np.hanning(len(y))))
        fq = np.fft.rfftfreq(len(y), dt)
        return np.sqrt(np.sum(Y[np.abs(fq - fr) < 40] ** 2))

    ig = (v['m'] - v['mg']) / 1.6e3             # grid current through the 1.6k grid noise resistor
    burst = (t > T0 + 0.02) & (t < T1)
    r = dict(ig_pk=float(np.max(ig[burst])) * 1e6, ig_avg=float(np.mean(ig[burst])) * 1e6)
    for n in ('rsig', 'nw', 'wmx', 'm', 'OUT'):
        r[n + '_pk'] = float(np.max(np.abs(win(v[n], T0 + 0.1, T1))))
    r['rp_min'], r['rp_max'] = float(np.min(win(v['rp'], T0 + 0.1, T1))), float(np.max(win(v['rp'], T0 + 0.1, T1)))
    p0 = tone(v['OUT'], 0.05, 0.09, 3000)           # same 40 ms window as the windows after
    rec = {}
    for ta in (0.41, 0.45, 0.50, 0.60, 0.80, 0.95):
        rec[ta] = 20 * np.log10(tone(v['OUT'], ta, ta + 0.04, 3000) / p0)
    r['rec'] = rec
    pre = lambda n: float(np.mean(win(v[n], 0.05, 0.10)))
    post = lambda n, ta: float(np.mean(win(v[n], ta, ta + 0.02)))
    for n in ('mg', 'rk', 'gwj', 'wmx'):
        r[n + '_dc'] = (pre(n), post(n, 0.41), post(n, 0.6), post(n, 0.95))
    return a, r


def main():
    jobs = [(17.0, False), (17.0, True), (9.0, False)]
    with Pool(len(jobs)) as p:
        res = dict(p.map(job, jobs))
    L = ['# Normalled return at full level', '', '> Generated by `run_normalled.py` (fx_revb.py circuit, generic NJFET, 12AX7 model).', '',
         'Series mode, return pot at full, 300 ms burst of 1 kHz at the given peak on RETURN_SIG plus a 0.3 V / 3 kHz probe.', '',
         '| RETURN_SIG peak | Pad | Grid current peak / average (µA) | nw / wmx / m peak (V) | Plate min / max (V) | Out peak (V) | Probe after the burst at 10 / 50 / 100 / 200 / 400 / 550 ms (dB) |',
         '|---|---|---|---|---|---|---|']
    for (amp, pad), r in res.items():
        if 'error' in r:
            L.append(f'| {amp} | {pad} | failed | | | | |')
            continue
        rc = ' / '.join(f'{x:+.1f}' for x in r['rec'].values())
        L.append(f"| {amp:.0f} V | {'-20 dB' if pad else '0 dB'} | {r['ig_pk']:.1f} / {r['ig_avg']:.2f} | "
                 f"{r['nw_pk']:.1f} / {r['wmx_pk']:.1f} / {r['m_pk']:.1f} | {r['rp_min']:.0f} / {r['rp_max']:.0f} | {r['OUT_pk']:.1f} | {rc} |")
    L += ['', 'DC levels before / 10 ms / 200 ms / 550 ms after the burst (V):', '',
          '| RETURN_SIG peak | Pad | Return grid (mg) | Cathode (rk) | Wet series JFET gate | Wet mixer node (wmx) |', '|---|---|---|---|---|---|']
    for (amp, pad), r in res.items():
        if 'error' in r:
            continue
        f = lambda k: ' / '.join(f'{x:+.2f}' for x in r[k])
        L.append(f"| {amp:.0f} V | {'-20 dB' if pad else '0 dB'} | {f('mg_dc')} | {f('rk_dc')} | {f('gwj_dc')} | {f('wmx_dc')} |")
    open(os.path.join(HERE, 'results', 'normalled.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
